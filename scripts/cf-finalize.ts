// The last step of `pnpm run build:cf` (after `NEXT_OUTPUT=export pnpm run build`): turns out/ into
// the Workers Static Assets directory that wrangler.jsonc deploys, then proves the export complete.
//
// Writes
//   out/_redirects    the 301s next.config.js redirects() serves on Vercel
//   out/_headers      HSTS, noindex for every non-canonical host (middleware.ts on Vercel), caching
//   out/.assetsignore build logs under public/ that nothing references
//
// Asserts (every problem is listed, then the step fails)
//   - out/index.html and out/404.html exist, and no API route or middleware leaked into out/
//   - every sitemap URL, and every noindex article, is an HTML file whose #arc-page-content holds
//     the page's text (for an article: every block of its record), with the right robots meta and
//     the canonical origin
//   - every slug the scene can open (archive index, films, search index docs) is exported, with
//     the _next/data JSON a client-side navigation fetches, so no in-scene link hard-reloads to 404
//   - the must-serve files (resumes, favicon, social preview, robots, sitemaps) are present
//   - the Static Assets limits hold: _headers rules and lines, one splat per rule, file count and
//     size
//
// The _headers and _redirects files apply only to static-asset responses. worker/index.ts sets the
// equivalent headers (worker/policy.ts, shared with this file) on what it answers itself: /api/*
// and the film directories it serves with byte ranges.

import fs from 'node:fs'
import path from 'node:path'
import { SITE_URL } from '../lib/site-url'
import { metaContent, planSitemaps, robotsMeta, type SitemapPlan } from './generate-sitemaps'
import { DATA_CACHE, FONT_CACHE, HSTS, IMMUTABLE, MEDIA_CACHE, NOINDEX } from '../worker/policy'

export { DATA_CACHE, FONT_CACHE, HSTS, IMMUTABLE, MEDIA_CACHE, NOINDEX }

// ---- _redirects -------------------------------------------------------------------------------

export interface RedirectRule {
  from: string
  to: string
  status: 301 | 302 | 307 | 308
}

/** next.config.js redirects(), in the same order. */
export const REDIRECTS: RedirectRule[] = [
  // /explore was retired: the 3D experience starts directly from /
  { from: '/explore', to: '/', status: 301 },
  // The MDX sources' old public URLs
  { from: '/docs/articles', to: '/articles', status: 301 },
  { from: '/docs/articles/*', to: '/articles/:splat', status: 301 },
]

export function redirectsFile(rules: RedirectRule[] = REDIRECTS): string {
  const lines = rules.map(({ from, to, status }) => `${from} ${to} ${status}`)
  return `# Generated by scripts/cf-finalize.ts; do not edit.\n${lines.join('\n')}\n`
}

// ---- _headers ---------------------------------------------------------------------------------

export interface HeaderRule {
  /** A path or an https URL; at most one splat, and each :placeholder used once. */
  pattern: string
  headers: Record<string, string>
}

/**
 * Hosts that must stay out of the index: the Worker's workers.dev URL and its version/preview URLs
 * (both <name>.<account>.workers.dev; a host placeholder stops at a dot) and the staging domain.
 */
export const NOINDEX_HOSTS = [
  'https://:version.:subdomain.workers.dev/*',
  'https://next.alexwelcing.com/*',
]

/**
 * The only immutable paths: prefixes whose every file name changes with its content. Next's
 * /_next/static holds hashed chunks plus a per-build directory. A future hashed asset family gets
 * its own prefix here (e.g. /worlds/_h/ for hashed sky textures), never a second splat in one rule
 * or an extension rule over unhashed names.
 */
export const IMMUTABLE_PREFIXES = ['/_next/static/']

export const HEADER_RULES: HeaderRule[] = [
  { pattern: '/*', headers: { 'Strict-Transport-Security': HSTS } },
  ...NOINDEX_HOSTS.map((pattern) => ({ pattern, headers: { 'X-Robots-Tag': NOINDEX } })),
  ...IMMUTABLE_PREFIXES.map((prefix) => ({
    pattern: `${prefix}*`,
    headers: { 'Cache-Control': IMMUTABLE },
  })),
  // /videos/<slug> are HTML pages (default revalidation); only the films under it are media.
  ...['/images/*', '/background/*', '/sounds/*', '/videos/articles/*', '/worlds/*', '/basis/*'].map(
    (pattern) => ({
      pattern,
      headers: { 'Cache-Control': MEDIA_CACHE },
    })
  ),
  { pattern: '/fonts/*', headers: { 'Cache-Control': FONT_CACHE } },
  ...['/arc/*', '/search/*'].map((pattern) => ({
    pattern,
    headers: { 'Cache-Control': DATA_CACHE },
  })),
]

/** Cloudflare's _headers limits (developers.cloudflare.com/workers/static-assets/headers/). */
export const HEADERS_LIMITS = { rules: 100, lineChars: 2000 }

/** Why a rule set is invalid for Workers Static Assets; empty when it is valid. */
export function headerRuleProblems(rules: HeaderRule[]): string[] {
  const problems: string[] = []
  if (rules.length > HEADERS_LIMITS.rules) {
    problems.push(`${rules.length} header rules (the limit is ${HEADERS_LIMITS.rules})`)
  }
  const cachePrefixes: string[] = []
  for (const { pattern, headers } of rules) {
    const splats = pattern.split('*').length - 1
    if (splats > 1) problems.push(`${pattern}: ${splats} splats (only one is allowed per rule)`)
    if (!pattern.startsWith('/') && !pattern.startsWith('https://')) {
      problems.push(`${pattern}: a rule is a path or an https:// URL`)
    }
    const placeholders = pattern.match(/:[A-Za-z]\w*/g) ?? []
    if (new Set(placeholders).size !== placeholders.length) {
      problems.push(`${pattern}: a placeholder is used twice`)
    }
    for (const [name, value] of Object.entries(headers)) {
      if (`  ${name}: ${value}`.length > HEADERS_LIMITS.lineChars) {
        problems.push(`${pattern}: the ${name} line is over ${HEADERS_LIMITS.lineChars} chars`)
      }
      if (name.toLowerCase() !== 'cache-control') continue
      cachePrefixes.push(pattern.replace(/\*$/, ''))
      const hashedPrefix = IMMUTABLE_PREFIXES.some((prefix) => pattern === `${prefix}*`)
      if (/\bimmutable\b/.test(value) && !hashedPrefix) {
        problems.push(`${pattern}: immutable outside the content-hashed prefixes`)
      }
    }
  }
  // Matching rules merge, and a header set twice is comma-joined, so no two Cache-Control rules
  // may ever match the same path.
  cachePrefixes.forEach((a, i) => {
    cachePrefixes.forEach((b, j) => {
      if (i !== j && b.startsWith(a)) problems.push(`Cache-Control rules ${a}* and ${b}* overlap`)
    })
  })
  return problems
}

export function headersFile(rules: HeaderRule[] = HEADER_RULES): string {
  const blocks = rules.map(({ pattern, headers }) =>
    [pattern, ...Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`)].join('\n')
  )
  return `# Generated by scripts/cf-finalize.ts; do not edit.\n${blocks.join('\n\n')}\n`
}

// ---- .assetsignore ----------------------------------------------------------------------------

/** Files under public/ that ship with the export but nothing references: generation logs. */
export const ASSETS_IGNORE = ['images/article-videos/*.json', 'assets/asset-costs.json']

/** A gitignore-style pattern (only `*`, within one segment) as a regex over out/-relative paths. */
function ignoreRegex(pattern: string): RegExp {
  const body = pattern
    .split('*')
    .map((part) => part.replace(/[.+?^${}()|[\]\\]/g, '\\$&'))
    .join('[^/]*')
  return new RegExp(`^${body}$`)
}

export function isIgnored(relative: string, patterns: string[] = ASSETS_IGNORE): boolean {
  return patterns.some((pattern) => ignoreRegex(pattern).test(relative))
}

// ---- Export verification ----------------------------------------------------------------------

/** Workers Static Assets limits: files per version (Free / Paid) and bytes per file. */
export const ASSET_LIMITS = { filesFree: 20_000, filesPaid: 100_000, fileBytes: 25 * 1024 * 1024 }

/** Present in out/, or links from outside the site (job applications, search results) break. */
export const MUST_SERVE = [
  'favicon.ico',
  'robots.txt',
  'social-preview.png',
  'og-default.png',
  'sitemap.xml',
  'video-sitemap.xml',
  'arc/archive.json',
  'arc/archive-full.json',
  'arc/media.json',
]
/** Every file in these public/ directories must be in out/ as well. */
export const MUST_SERVE_DIRS = ['resumes', 'fonts']

/** Text shorter than this inside #arc-page-content means a page exported without its body. */
export const MIN_PAGE_TEXT = 80

/** The out/ file html_handling 'auto-trailing-slash' serves for a route. */
export function htmlFileFor(route: string): string {
  const page = route.replace(/^\/+|\/+$/g, '')
  return page ? `${page}.html` : 'index.html'
}

const ENTITY: Record<string, string> = {
  amp: '&',
  lt: '<',
  gt: '>',
  quot: '"',
  apos: "'",
  nbsp: ' ',
}

export function decodeEntities(text: string): string {
  return text.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (match, code: string) => {
    if (code[0] !== '#') return ENTITY[code.toLowerCase()] ?? match
    const hex = code[1].toLowerCase() === 'x'
    const point = hex ? parseInt(code.slice(2), 16) : Number(code.slice(1))
    return Number.isInteger(point) && point >= 0 && point <= 0x10ffff
      ? String.fromCodePoint(point)
      : match
  })
}

export const collapse = (text: string) => text.replace(/\s+/g, ' ').trim()

/**
 * The visible text of a page's #arc-page-content, or null when the page has none. It stops at
 * __NEXT_DATA__, whose props repeat the body as JSON and would hide a page that rendered empty.
 */
export function pageContentText(html: string): string | null {
  const start = html.indexOf('<div id="arc-page-content"')
  if (start < 0) return null
  const end = html.indexOf('<script id="__NEXT_DATA__"', start)
  const segment = html
    .slice(start, end < 0 ? undefined : end)
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<(script|style|template)\b[\s\S]*?<\/\1>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
  return collapse(decodeEntities(segment))
}

function canonicalHref(html: string): string | null {
  for (const tag of html.match(/<link\b[^>]*>/gi) ?? []) {
    if (/\brel="canonical"/i.test(tag)) return /\bhref="([^"]*)"/i.exec(tag)?.[1] ?? ''
  }
  return null
}

function walk(dir: string, rel = ''): { relative: string; bytes: number }[] {
  const files: { relative: string; bytes: number }[] = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const relative = rel ? `${rel}/${entry.name}` : entry.name
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) files.push(...walk(full, relative))
    else if (entry.isFile()) files.push({ relative, bytes: fs.statSync(full).size })
  }
  return files
}

const readJson = <T>(file: string): T => JSON.parse(fs.readFileSync(file, 'utf8')) as T

export interface ExportReport {
  problems: string[]
  warnings: string[]
  /** HTML pages whose text was checked. */
  pages: number
  /** Deployed asset files (after .assetsignore) and their total size. */
  files: number
  bytes: number
}

interface RecordFile {
  blocks: { t: string; x: string }[]
}

/** Checks out/ under root against the content it must serve. Reads files only. */
export function verifyExport(
  root: string,
  plan: SitemapPlan = planSitemaps(root),
  siteUrl = SITE_URL
): ExportReport {
  const out = path.join(root, 'out')
  const problems: string[] = []
  const warnings: string[] = []
  const exists = (relative: string) => fs.existsSync(path.join(out, relative))

  for (const file of ['index.html', '404.html']) {
    if (!exists(file)) problems.push(`out/${file} is missing`)
  }
  for (const leak of ['api', 'api.html', 'middleware.js', '_next/server']) {
    if (exists(leak)) problems.push(`out/${leak} exists: the server surface leaked into the export`)
  }

  const dataDirs = exists('_next/data') ? fs.readdirSync(path.join(out, '_next/data')) : []
  if (dataDirs.length !== 1) {
    problems.push(`out/_next/data has ${dataDirs.length} build directories (expected 1)`)
  }
  const dataFile = (route: string) => `_next/data/${dataDirs[0]}${route}.json`

  // Pages: text, robots, canonical.
  let pages = 0
  const checkPage = (route: string, expectNoindex: boolean, blocks?: RecordFile['blocks']) => {
    const file = htmlFileFor(route)
    if (!exists(file)) {
      problems.push(`${route}: out/${file} is missing`)
      return
    }
    pages += 1
    const html = fs.readFileSync(path.join(out, file), 'utf8')
    const text = pageContentText(html)
    if (text === null) {
      problems.push(`${route}: no #arc-page-content`)
      return
    }
    if (text.length < MIN_PAGE_TEXT) {
      problems.push(`${route}: #arc-page-content holds only ${text.length} chars of text`)
    }
    const missing = (blocks ?? []).filter((block) => !text.includes(collapse(block.x)))
    if (missing.length) {
      const sample = collapse(missing[0].x).slice(0, 60)
      problems.push(`${route}: ${missing.length} record blocks are not in the HTML ("${sample}…")`)
    }
    const robots = robotsMeta(html) ?? ''
    if (/noindex/i.test(robots) !== expectNoindex) {
      const expected = expectNoindex ? 'noindex' : 'indexable'
      problems.push(`${route}: robots "${robots || '(none)'}", expected ${expected}`)
    }
    const canonical = canonicalHref(html)
    if (canonical !== null && !canonical.startsWith(siteUrl)) {
      problems.push(`${route}: canonical ${canonical} is not on ${siteUrl}`)
    }
    if (!metaContent(html, 'description')) warnings.push(`${route}: no meta description`)
  }

  const recordBlocks = (slug: string) =>
    readJson<RecordFile>(path.join(root, 'public', 'arc', 'records', `${slug}.json`)).blocks
  for (const { path: route } of plan.urls) {
    const article = /^\/articles\/([^/]+)$/.exec(route)?.[1]
    checkPage(route, false, article ? recordBlocks(article) : undefined)
  }
  for (const { slug } of plan.noindex) checkPage(`/articles/${slug}`, true, recordBlocks(slug))

  // Every slug the scene can open must be exported with its client-navigation data.
  const openable = new Map<string, string>()
  const openableFrom = (route: string, source: string) => {
    if (!openable.has(route)) openable.set(route, source)
  }
  const archive = readJson<{ records: { slug: string }[] }>(
    path.join(root, 'public', 'arc', 'archive.json')
  )
  for (const { slug } of archive.records) openableFrom(`/articles/${slug}`, 'arc/archive.json')
  const media = readJson<{ films: string[] }>(path.join(root, 'public', 'arc', 'media.json'))
  for (const slug of media.films) openableFrom(`/videos/${slug}`, 'arc/media.json')
  const searchManifest = readJson<{ assets?: { chunks?: string } }>(
    path.join(root, 'lib', 'generated', 'search-manifest.json')
  )
  const chunksAsset = searchManifest.assets?.chunks
  if (chunksAsset && exists(chunksAsset.slice(1))) {
    const { docs } = readJson<{ docs: { slug: string; target: { type: string } }[] }>(
      path.join(out, chunksAsset.slice(1))
    )
    for (const doc of docs) {
      if (doc.target.type === 'article') openableFrom(`/articles/${doc.slug}`, chunksAsset)
    }
  } else {
    problems.push(`the search index ${chunksAsset ?? '(none in the manifest)'} is not in out/`)
  }
  for (const [route, source] of openable) {
    if (!exists(htmlFileFor(route))) problems.push(`${route} (from ${source}) is not exported`)
    else if (dataDirs.length === 1 && !exists(dataFile(route))) {
      problems.push(`${route} (from ${source}) has no out/${dataFile(route)}`)
    }
  }

  // Must-serve files.
  for (const file of MUST_SERVE) if (!exists(file)) problems.push(`out/${file} is missing`)
  for (const dir of MUST_SERVE_DIRS) {
    const source = path.join(root, 'public', dir)
    if (!fs.existsSync(source)) continue
    for (const { relative } of walk(source)) {
      if (!exists(`${dir}/${relative}`)) problems.push(`out/${dir}/${relative} is missing`)
    }
  }
  // The sitemap that ships lists exactly the plan's URLs, all exported.
  if (exists('sitemap.xml')) {
    const xml = fs.readFileSync(path.join(out, 'sitemap.xml'), 'utf8')
    const locs = [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map((match) => match[1])
    if (locs.length !== plan.urls.length) {
      problems.push(`out/sitemap.xml lists ${locs.length} URLs, the plan ${plan.urls.length}`)
    }
    for (const loc of locs) {
      const route = loc.startsWith(siteUrl) ? loc.slice(siteUrl.length) || '/' : null
      if (route === null) problems.push(`out/sitemap.xml lists ${loc}, not on ${siteUrl}`)
      else if (!exists(htmlFileFor(route))) {
        problems.push(`out/sitemap.xml lists ${loc}, which is not exported`)
      }
    }
  }

  // Static Assets limits.
  const files = walk(out).filter(
    ({ relative }) =>
      !['_headers', '_redirects', '.assetsignore'].includes(relative) && !isIgnored(relative)
  )
  const bytes = files.reduce((sum, file) => sum + file.bytes, 0)
  for (const file of files) {
    if (file.bytes > ASSET_LIMITS.fileBytes) {
      problems.push(`out/${file.relative} is ${file.bytes} bytes (the per-file limit is 25 MiB)`)
    }
  }
  if (files.length > ASSET_LIMITS.filesPaid) {
    problems.push(`${files.length} asset files (the Paid limit is ${ASSET_LIMITS.filesPaid})`)
  } else if (files.length > ASSET_LIMITS.filesFree) {
    warnings.push(`${files.length} asset files: over the Free plan's ${ASSET_LIMITS.filesFree}`)
  }
  problems.push(...headerRuleProblems(HEADER_RULES))

  return { problems, warnings, pages, files: files.length, bytes }
}

export function finalize(root: string = process.cwd()): ExportReport {
  const out = path.join(root, 'out')
  if (!fs.existsSync(out)) {
    throw new Error('[cf-finalize] out/ does not exist: run `NEXT_OUTPUT=export pnpm run build`')
  }
  fs.writeFileSync(path.join(out, '_redirects'), redirectsFile())
  fs.writeFileSync(path.join(out, '_headers'), headersFile())
  fs.writeFileSync(
    path.join(out, '.assetsignore'),
    `# Generated by scripts/cf-finalize.ts; do not edit.\n${ASSETS_IGNORE.join('\n')}\n`
  )
  const report = verifyExport(root)
  for (const warning of report.warnings) console.warn(`[cf-finalize] warning: ${warning}`)
  if (report.problems.length) {
    throw new Error(
      `[cf-finalize] the export is incomplete (${report.problems.length} problems):\n  ` +
        report.problems.join('\n  ')
    )
  }
  const mib = (report.bytes / 1024 / 1024).toFixed(1)
  console.log(
    `[cf-finalize] out/ verified: ${report.pages} pages with their full #arc-page-content text, ` +
      `${report.files} asset files (${mib} MiB), ${REDIRECTS.length} redirects, ` +
      `${HEADER_RULES.length} header rules`
  )
  return report
}

// CLI entry. Importing the module (the tests) only defines the functions.
if (/cf-finalize\.ts$/.test(process.argv[1] ?? '')) {
  try {
    finalize()
  } catch (err) {
    console.error(err instanceof Error ? err.message : err)
    process.exit(1)
  }
}
