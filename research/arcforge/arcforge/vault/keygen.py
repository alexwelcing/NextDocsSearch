"""`arcforge vault keygen`: make the owner's vault key, once, in the owner's own terminal.

The identity is generated by age-keygen into memory and never written to a file. The owner sees
it exactly once, saves it to a password manager (plus one offline copy), and proves the saved
copy is intact by pasting it back, hidden. Only then is the public recipient written to
configs/vault.recipient (safe to commit) and the screen and scrollback cleared.

It refuses to run unless stdin and stdout are both a terminal: an agent or a script that ran it
would capture the private key in its transcript or logs.
"""

from __future__ import annotations

import getpass
import sys
from collections.abc import Callable
from pathlib import Path
from typing import TextIO

from arcforge.owner.store import utc_now, write_bytes_atomic
from arcforge.vault import age

CLEAR_SCREEN = '\033[2J\033[3J\033[H'  # clear the screen, then the scrollback (Terminal, iTerm)
VERIFY_TRIES = 3


class KeygenError(Exception):
    pass


def interactive() -> bool:
    return sys.stdin.isatty() and sys.stdout.isatty()


def recipient_text(recipient: str) -> str:
    return (
        '# The RE-MEANING vault recipient: the owner’s public age key. Safe to commit.\n'
        f'# Created {utc_now()} by `arcforge vault keygen`. The private key is held only by the owner.\n'
        f'{recipient}\n'
    )


def keygen(
    recipient_file: Path,
    *,
    force: bool = False,
    is_interactive: Callable[[], bool] = interactive,
    ask: Callable[[str], str] = input,
    ask_hidden: Callable[[str], str] = getpass.getpass,
    out: TextIO | None = None,
) -> str:
    """Run the ceremony; returns the recipient written to `recipient_file`."""
    out = out or sys.stdout
    if recipient_file.exists() and not force:
        raise KeygenError(
            f'{recipient_file} already exists. A new key would orphan everything sealed to the old '
            'one. If you really mean to replace it (nothing is sealed yet), rerun with --force.'
        )
    if not is_interactive():
        raise KeygenError(
            'run this yourself in Terminal, not through an agent or a pipe: it shows the private '
            'key, and anything capturing this output would keep a copy.'
        )
    identity, recipient = age.generate_identity()
    rule = '─' * 74
    print(
        f'\n{rule}\n  YOUR VAULT KEY  (shown once, never stored)\n{rule}\n\n  {identity}\n\n{rule}\n'
        '  1. Save it in your password manager as "arc vault key".\n'
        '  2. Make one offline copy (paper, or a USB stick kept apart).\n'
        '  3. Never paste it into chat, an agent, the repo, the VM, GCS or HF.\n'
        '     Only `arcforge vault read` on this laptop ever asks for it (R04, R06/R07, R10).\n'
        f'{rule}\n',
        file=out,
        flush=True,
    )
    while ask('Type SAVED once both copies exist (or Ctrl-C to abandon this key): ').strip() != 'SAVED':
        print('  Not yet: type SAVED, in capitals.', file=out)
    for attempt in range(1, VERIFY_TRIES + 1):
        pasted = ask_hidden('Now paste it back from your password manager (hidden) to check it: ')
        if pasted.strip() == identity:
            break
        left = VERIFY_TRIES - attempt
        if not left:
            raise KeygenError(
                'the pasted key never matched, so nothing was written and this key is abandoned. '
                'Delete the saved copy and run keygen again.'
            )
        print(f'  That does not match what was shown. {left} more tries.', file=out)
    write_bytes_atomic(recipient_file, recipient_text(recipient).encode('utf-8'), mode=0o644)
    cleared = bool(getattr(out, 'isatty', lambda: False)())
    if cleared:
        out.write(CLEAR_SCREEN)
    print(
        'Vault key saved by you, and only by you.' + (' The screen was cleared.' if cleared else '') + '\n'
        f'Public recipient written to {recipient_file}:\n  {recipient}\n'
        'It is safe to commit. Nothing secret was written anywhere.',
        file=out,
    )
    return recipient
